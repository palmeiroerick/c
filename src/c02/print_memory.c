#include "libc.h"

int is_print(unsigned char c) {
    return c >= ' ' && c <= '~';
}

void *print_memory(void *address, size_t size) {
    size_t i = 0;

    unsigned char *data = (unsigned char *)address;

    while (i < size) {
        if (i > 0 && i % 16 == 0) {
            c_putchar('\n');
        }
        if (is_print(data[i])) {
            c_putchar((char)data[i]);
        }
        else {
            c_putchar('.');
        }
        i++;
    }

    return address;
}

